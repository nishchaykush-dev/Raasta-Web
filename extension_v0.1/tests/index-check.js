const {chromium}=require("playwright");
const path=require("path");
(async()=>{
  const b=await chromium.launch({channel:"chromium",headless:true,args:["--no-sandbox"]});
  const p=await b.newPage({viewport:{width:1100,height:900}});
  const errs=[]; p.on("pageerror",e=>errs.push(e.message)); p.on("console",m=>{if(m.type()==="error")errs.push(m.text())});
  await p.goto("file://"+path.resolve("index.html"));
  let ok=true; const chk=(n,c,d)=>{console.log((c?"  PASS  ":"  FAIL  ")+n+(c||!d?"":"  -> "+d)); if(!c)ok=false;};
  const li=async()=>p.locator("#ext li").allInnerTexts();
  let items=await li();
  chk("Hindi: 4 steps filled", items.length===4 && items.every(x=>x.length>10), JSON.stringify(items));
  chk("Hindi title", /सारथी/.test(await p.locator("#et").innerText()));
  await p.locator('[data-lang="en"]').click();
  items=await li();
  chk("English: 4 steps filled", items.length===4 && /Developer mode/.test(items[0]), JSON.stringify(items));
  chk("English title", await p.locator("#et").innerText()==="Use Saarthi on any website");
  chk("English note present", /never presses or types/.test(await p.locator("#ext .note").innerText()));
  const r=await p.evaluate(()=>({a:SaarthiLauncher.clean("example.com"),b:SaarthiLauncher.clean("javascript:alert(1)"),c:SaarthiLauncher.clean("portal.html"),d:typeof SaarthiLauncher.launchUrl}));
  chk("launcher URL check still works", r.a.url==="https://example.com/" && r.b.code==="errScheme" && /portal\.html$/.test(r.c.url), JSON.stringify(r));
  await p.screenshot({path:"tests/shots/6-index-en.png",fullPage:true});
  await p.locator('[data-lang="hi"]').click();
  await p.screenshot({path:"tests/shots/7-index-hi.png",fullPage:true});
  chk("no script errors", errs.length===0, errs.join(" | "));
  await b.close(); process.exit(ok?0:1);
})();
